/** Mensagens com números variáveis (antecedência mínima, capacidade). */
const SERVER_PATTERNS: { re: RegExp; t: Record<Exclude<Locale, "pt">, (...m: string[]) => string> }[] = [
  {
    re: /^Os pedidos são feitos com pelo menos (\d+) dia\(s\) de antecedência\.$/,
    t: {
      es: (n) => `Las solicitudes se hacen con al menos ${n} día(s) de antelación.`,
      fr: (n) => `Les demandes se font au moins ${n} jour(s) à l’avance.`,
      en: (n) => `Requests must be made at least ${n} day(s) in advance.`,
    },
  },
  {
    re: /^Esta experiência é para (\d+) pessoa\(s\)\.$/,
    t: {
      es: (n) => `Esta experiencia es para ${n} persona(s).`,
      fr: (n) => `Cette expérience est prévue pour ${n} personne(s).`,
      en: (n) => `This experience is for ${n} ${n === "1" ? "person" : "people"}.`,
    },
  },
  {
    re: /^Entre (\d+) e (\d+) pessoas por reserva\.$/,
    t: {
      es: (a, b) => `Entre ${a} y ${b} personas por reserva.`,
      fr: (a, b) => `Entre ${a} et ${b} personnes par réservation.`,
      en: (a, b) => `Between ${a} and ${b} people per booking.`,
    },
  },
];

export function translateServerMessage(locale: Locale, message: string | undefined): string | undefined {
  if (!message || locale === "pt") return message;
  const direct = SERVER[locale][message];
  if (direct) return direct;
  for (const { re, t } of SERVER_PATTERNS) {
    const match = message.match(re);
    if (match) return t[locale](...match.slice(1));
  }
  return message;
}
