/** Plural russo: 1 человек / 2–4 человека / 5+ человек. */
const ruPlural = (n: number, one: string, few: string, many: string) => {
  const a = n % 10;
  const b = n % 100;
  if (a === 1 && b !== 11) return `${n} ${one}`;
  if (a >= 2 && a <= 4 && (b < 12 || b > 14)) return `${n} ${few}`;
  return `${n} ${many}`;
};
const ruPeople = (n: number) => ruPlural(n, "человек", "человека", "человек");
const ruDays = (n: number) => ruPlural(n, "день", "дня", "дней");

